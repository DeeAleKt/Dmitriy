const enc = new TextEncoder();

// Стилі клітинок (індекси cellXfs у styles.xml)
export const STYLE = { text: 0, header: 1, decimal: 2, int: 3, bold: 4, boldDecimal: 5, date: 6 };

/** Дата 'YYYY-MM-DD' → порядковий номер дня Excel */
export function excelDate(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return Date.UTC(y, m - 1, d) / 86400000 + 25569;
}

