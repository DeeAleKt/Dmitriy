// Жарт не змінюється на кожну цифру: лише зі станом дня, раз на 10 хв або коли його торкнутися.
// Свої рядки можна дописати в QUIPS; порожній список — під відсотком нічого. Розрахунок від цього не залежить.

/** Простий стійкий хеш рядка — щоб жарт не мінявся на кожну цифру. */
function hash(s) {
  let h = 2166136261;
  for (const ch of String(s)) h = Math.imul(h ^ ch.codePointAt(0), 16777619);
  return h >>> 0;
}

