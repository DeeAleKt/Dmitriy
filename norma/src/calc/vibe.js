// Прайд-режим: голос застосунку — веселка, блиск і жарти. Рахує все так само, це лише слова навколо цифр.
// Гумор — camp і драг-«шейд»: дива гостро «читає» за темп і відсоток, але без лайки, образ людей
// і пошлості — це робочий інструмент, його бачать колеги й адміністратор. Вимикається в «Налаштування → Вигляд».

/** Простий стійкий хеш рядка — щоб жарт не мінявся на кожну цифру, а лише зі станом чи часом. */
function hash(s) {
  let h = 2166136261;
  for (const ch of String(s)) h = Math.imul(h ^ ch.codePointAt(0), 16777619);
  return h >>> 0;
}

